-- =========================================================
-- Примеры запросов
-- =========================================================

-- 1. Вывести все бронирования с информацией о клиенте,
--    отеле и виде тура

SELECT
    b.booking_id,
    c.first_name || ' ' || c.last_name AS client_name,
    h.hotel_name,
    h.country,
    h.city,
    t.tour_name,
    b.departure_date,
    b.return_date,
    b.tourists_count,
    b.total_price,
    b.status
FROM bookings AS b
JOIN clients AS c
    ON b.client_id = c.client_id
JOIN hotels AS h
    ON b.hotel_id = h.hotel_id
JOIN tour_types AS t
    ON b.tour_type_id = t.tour_type_id
ORDER BY b.departure_date;

-- 2. Найти все оплаченные бронирования

SELECT
    booking_id,
    client_id,
    hotel_id,
    tour_type_id,
    total_price
FROM bookings
WHERE status = 'Оплачено';

-- 3. Посчитать количество бронирований для каждого отеля

SELECT
    h.hotel_name,
    COUNT(b.booking_id) AS bookings_count
FROM hotels AS h
LEFT JOIN bookings AS b
    ON h.hotel_id = b.hotel_id
GROUP BY h.hotel_id, h.hotel_name
ORDER BY bookings_count DESC;

-- 4. Найти клиентов, у которых есть хотя бы одно бронирование

SELECT DISTINCT
    c.client_id,
    c.first_name,
    c.last_name,
    c.email
FROM clients AS c
JOIN bookings AS b
    ON c.client_id = b.client_id;

-- 5. Посчитать общую стоимость всех активных заказов

SELECT
    SUM(total_price) AS total_active_bookings_price
FROM bookings
WHERE status IN ('Оформлено', 'Оплачено');

-- 6. Найти самые дорогие туры

SELECT
    tour_name,
    duration_days,
    base_price
FROM tour_types
ORDER BY base_price DESC;
