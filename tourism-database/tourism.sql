-- Удаление таблиц при повторном запуске скрипта
DROP TABLE IF EXISTS bookings CASCADE;
DROP TABLE IF EXISTS tour_types CASCADE;
DROP TABLE IF EXISTS hotels CASCADE;
DROP TABLE IF EXISTS clients CASCADE;

-- =========================================================
-- Таблица клиентов
-- =========================================================

CREATE TABLE clients (
    client_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(50) NOT NULL,
    last_name VARCHAR(50) NOT NULL,
    phone VARCHAR(20) NOT NULL UNIQUE,
    email VARCHAR(100) NOT NULL UNIQUE,
    passport_number VARCHAR(20) NOT NULL UNIQUE,
    registration_date DATE NOT NULL DEFAULT CURRENT_DATE
);

-- =========================================================
-- Таблица отелей
-- =========================================================

CREATE TABLE hotels (
    hotel_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hotel_name VARCHAR(100) NOT NULL,
    country VARCHAR(50) NOT NULL,
    city VARCHAR(50) NOT NULL,
    stars SMALLINT NOT NULL CHECK (stars BETWEEN 1 AND 5),
    address VARCHAR(150) NOT NULL
);

-- =========================================================
-- Таблица видов туров
-- =========================================================

CREATE TABLE tour_types (
    tour_type_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tour_name VARCHAR(100) NOT NULL UNIQUE,
    description TEXT,
    duration_days SMALLINT NOT NULL CHECK (duration_days > 0),
    base_price NUMERIC(10, 2) NOT NULL CHECK (base_price >= 0)
);

-- =========================================================
-- Таблица бронирований
-- =========================================================

CREATE TABLE bookings (
    booking_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    client_id INTEGER NOT NULL,
    hotel_id INTEGER NOT NULL,
    tour_type_id INTEGER NOT NULL,

    booking_date DATE NOT NULL DEFAULT CURRENT_DATE,
    departure_date DATE NOT NULL,
    return_date DATE NOT NULL,

    tourists_count SMALLINT NOT NULL CHECK (tourists_count > 0),
    total_price NUMERIC(12, 2) NOT NULL CHECK (total_price >= 0),

    status VARCHAR(20) NOT NULL DEFAULT 'Оформлено'
        CHECK (status IN ('Оформлено', 'Оплачено', 'Отменено', 'Завершено')),

    CONSTRAINT booking_dates_check
        CHECK (return_date > departure_date),

    CONSTRAINT bookings_client_fk
        FOREIGN KEY (client_id)
        REFERENCES clients(client_id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT bookings_hotel_fk
        FOREIGN KEY (hotel_id)
        REFERENCES hotels(hotel_id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT bookings_tour_type_fk
        FOREIGN KEY (tour_type_id)
        REFERENCES tour_types(tour_type_id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);

